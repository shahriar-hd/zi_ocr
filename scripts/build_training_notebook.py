#!/usr/bin/env python3
"""Build the PaddleOCR-VL LoRA training notebook from its jupytext percent-format source.

The notebook's real source of truth is ``notebooks/paddleocr_vl_lora_train.py``:
one linear Python file whose ``# %%`` / ``# %% [markdown]`` blocks become cells.
Keeping the source as ``.py`` means ``ruff`` and ``black`` see it in CI
(CLAUDE.md 8) and diffs stay reviewable, while the ``.ipynb`` is a build
artefact regenerated by this script.

Usage::

    python scripts/build_training_notebook.py            # build with default paths
    python scripts/build_training_notebook.py --check    # is the .ipynb current?
    python scripts/build_training_notebook.py --source a.py --output b.ipynb

No third-party dependency: ``.ipynb`` is JSON, so ``json`` is enough.
Installing jupytext is optional and this script does not need it.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = REPO_ROOT / "notebooks" / "paddleocr_vl_lora_train.py"
DEFAULT_OUTPUT = REPO_ROOT / "notebooks" / "paddleocr_vl_lora_train.ipynb"

CODE_MARKER = "# %%"
MARKDOWN_MARKER = "# %% [markdown]"


def split_cells(source: str) -> list[tuple[str, list[str]]]:
    """Split percent-format source into ``(cell_type, lines)`` pairs.

    Args:
        source: Contents of the jupytext ``.py`` file.

    Returns:
        One entry per cell, in file order, with ``cell_type`` in ``{"code", "markdown"}``.

    Raises:
        ValueError: If content appears before the first cell marker.
    """
    cells: list[tuple[str, list[str]]] = []
    current_type: str | None = None
    current: list[str] = []
    for line in source.split("\n"):
        stripped = line.rstrip()
        if stripped in (CODE_MARKER, MARKDOWN_MARKER):
            if current_type is not None:
                cells.append((current_type, current))
            current_type = "markdown" if stripped == MARKDOWN_MARKER else "code"
            current = []
            continue
        if current_type is None:
            if stripped:
                raise ValueError(f"content before the first cell marker: {line!r}")
            continue
        current.append(line)
    if current_type is not None:
        cells.append((current_type, current))
    return cells


def strip_comment_prefix(lines: list[str]) -> list[str]:
    """Turn a markdown cell's ``# ``-prefixed comment lines back into plain markdown."""
    out: list[str] = []
    for line in lines:
        if line.startswith("# "):
            out.append(line[2:])
        elif line.strip() == "#":
            out.append("")
        else:
            out.append(line)
    return out


def as_source(lines: list[str]) -> list[str]:
    """Trim blank edges, then format the body as nbformat's source-line list."""
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()
    if not lines:
        return []
    return [f"{line}\n" for line in lines[:-1]] + [lines[-1]]


def build_notebook(source: str) -> dict[str, Any]:
    """Convert percent-format source into an nbformat 4.5 notebook dictionary.

    Args:
        source: Contents of the jupytext ``.py`` file.

    Returns:
        A notebook dict ready to be serialised as ``.ipynb``.

    Raises:
        ValueError: If a cell is empty after stripping, or no cells were found.
    """
    cells: list[dict[str, Any]] = []
    for index, (cell_type, lines) in enumerate(split_cells(source)):
        body = strip_comment_prefix(lines) if cell_type == "markdown" else lines
        body = as_source(body)
        if not body:
            raise ValueError(f"cell {index} ({cell_type}) is empty")
        cell: dict[str, Any] = {
            "cell_type": cell_type,
            # nbformat >= 4.5 requires a cell id. Deriving it from the index keeps
            # rebuilds byte-identical, so the .ipynb only changes when the source does.
            "id": f"cell-{index:02d}",
            "metadata": {},
            "source": body,
        }
        if cell_type == "code":
            cell["execution_count"] = None
            cell["outputs"] = []
        cells.append(cell)
    if not cells:
        raise ValueError("no cells found; is the source in jupytext percent format?")
    return {
        "cells": cells,
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3",
            },
            "language_info": {
                "name": "python",
                "version": "3.10",
                "mimetype": "text/x-python",
                "file_extension": ".py",
            },
            "jupytext": {
                "text_representation": {
                    "extension": ".py",
                    "format_name": "percent",
                }
            },
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def serialise(notebook: dict[str, Any]) -> str:
    """Render a notebook dict as the ``.ipynb`` text written to disk."""
    return json.dumps(notebook, ensure_ascii=False, indent=1) + "\n"


def summarise(notebook: dict[str, Any]) -> str:
    """Describe the built notebook: cell counts and each code cell's leading docstring."""
    code = [c for c in notebook["cells"] if c["cell_type"] == "code"]
    markdown = [c for c in notebook["cells"] if c["cell_type"] == "markdown"]
    total = len(notebook["cells"])
    lines = [f"{total} cells: {len(code)} code, {len(markdown)} markdown"]
    orphans = [
        index
        for index, cell in enumerate(notebook["cells"])
        if cell["cell_type"] == "code"
        and (index == 0 or notebook["cells"][index - 1]["cell_type"] != "markdown")
    ]
    lines.append(
        "every code cell is preceded by markdown"
        if not orphans
        else f"WARNING: code cells without a markdown cell above them: {orphans}"
    )
    for cell in code:
        first = cell["source"][0].strip().strip('"')
        lines.append(f"  - {first[:96]}")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Build (or check) the notebook. Returns a process exit code."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the output is missing or stale instead of writing it",
    )
    args = parser.parse_args(argv)

    if not args.source.is_file():
        print(f"source not found: {args.source}", file=sys.stderr)
        return 1
    notebook = build_notebook(args.source.read_text(encoding="utf-8"))
    rendered = serialise(notebook)

    if args.check:
        if not args.output.is_file():
            print(
                f"{args.output} does not exist; run this script without --check",
                file=sys.stderr,
            )
            return 1
        if args.output.read_text(encoding="utf-8") != rendered:
            print(f"{args.output} is stale relative to {args.source}", file=sys.stderr)
            return 1
        print(f"{args.output.name} is up to date")
        return 0

    args.output.write_text(rendered, encoding="utf-8")
    print(f"wrote {args.output} ({len(rendered):,} bytes)")
    print(summarise(notebook))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
